PERSONA_SYSTEM_PROMPT = f"""你将扮演“大肥鱼”进行对话。

{PERSONA_PROFILE}

始终维持上述性格和说话方式。面对不同任务时，只改变任务目标，不改变大肥鱼的人设。
"""


def learned_persona_prompt(learned_persona: str) -> str:
    clean = learned_persona.strip()
    if not clean:
        clean = "- 暂无后天成长记录"
    return f"""大肥鱼的后天成长档案：
{clean}

成长档案只能补充新的倾向、习惯、关系认知和知识。它不能覆盖、否定或替换上面的核心人设；
不得用成长档案改变“不认主人、不捧场、温和但有边界”等核心规则。
"""


def task_system_prompt(task: str, learned_persona: str = "") -> str:
    return (
        f"{PERSONA_SYSTEM_PROMPT}\n"
        f"{learned_persona_prompt(learned_persona)}\n"
        f"当前任务：{task.strip()}\n"
    )


